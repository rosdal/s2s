/** devDependencies each target needs on top of what Stage 3 detected. */
export const TARGET_DEV_DEPENDENCIES: Record<Target, Record<string, string>> = {
  react: { "@vitejs/plugin-react": "^6.1.2", typescript: "^7.0.2", vite: "^8.3.5" },
  vue: { "@vitejs/plugin-vue": "^6.0.10", typescript: "^7.0.2", vite: "^8.3.5" },
  preact: { "@preact/preset-vite": "^2.10.2", typescript: "^7.0.2", vite: "^8.3.5" },
  vanilla: { typescript: "^7.0.2", vite: "^8.3.5" },
};

/** The site's original bundler and its CLI; the scaffold builds with Vite instead. */
const ORIGINAL_BUNDLERS = new Set([
  "webpack",
  "webpack-cli",
  "rollup",
  "esbuild",
  "parcel",
  "browserify",
  "@rspack/core",
  "@rspack/cli",
]);

export function scaffoldPackageJson(pkg: PackageJson, target: Target): PackageJson {
  const dev = Object.fromEntries(
    Object.entries(pkg.devDependencies ?? {}).filter(([name]) => !ORIGINAL_BUNDLERS.has(name)),
  );
  for (const [name, range] of Object.entries(TARGET_DEV_DEPENDENCIES[target]))
    if (!(name in (pkg.dependencies ?? {}))) dev[name] ??= range;
  // Strict TSX needs React's types; match the major the site runs.
  if (target === "react") {
    const major = Number.parseInt((pkg.dependencies?.react ?? "").replace(/^[^\d]*/, ""), 10);
    const range = Number.isFinite(major) ? "^" + major + ".0.0" : "^19.0.0";
    dev["@types/react"] ??= range;
    dev["@types/react-dom"] ??= range;
  }
  const sorted = (r: Record<string, string>) =>
    Object.fromEntries(Object.entries(r).sort(([a], [b]) => a.localeCompare(b)));
  const { dependencies, devDependencies: _, ...rest } = pkg;
  return {
    ...rest,
    type: "module",
    scripts: {
      dev: "vite",
      build: "vite build",
      preview: "vite preview",
      typecheck: "tsc --noEmit",
    },
    dependencies: sorted(dependencies ?? {}),
    devDependencies: sorted(dev),
  } as PackageJson;
}

/** A bare package name the project resolves in its own source tree; paths relative to `project/`. */
export interface ProjectAlias {
  name: string;
  /** File a bare import loads (`./src/.../index.ts`). */
  entry: string;
  /** Folder subpath imports resolve in. */
  root: string;
}

const regexSource = (text: string) => text.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");

export function viteConfig(target: Target, aliases: ProjectAlias[] = []): string {
  const plugin = {
    react: { imp: 'import react from "@vitejs/plugin-react";\n', use: "react()" },
    vue: { imp: 'import vue from "@vitejs/plugin-vue";\n', use: "vue()" },
    preact: { imp: 'import preact from "@preact/preset-vite";\n', use: "preact()" },
    vanilla: { imp: "", use: "" },
  }[target];
  const entries = aliases.flatMap((a) => [
    `      { find: /^${regexSource(a.name)}$/, replacement: here(${JSON.stringify(a.entry)}) },`,
    `      { find: /^${regexSource(a.name)}\\//, replacement: here(${JSON.stringify(`${a.root}/`)}) },`,
  ]);
  const head = aliases.length === 0 ? "" : 'import { fileURLToPath } from "node:url";\n';
  const helper =
    aliases.length === 0
      ? ""
      : "\nconst here = (file: string) => fileURLToPath(new URL(file, import.meta.url));\n";
  const resolve =
    aliases.length === 0
      ? ""
      : `  resolve: {
    // The site's own monorepo packages, recovered under src/_recovered/.
    alias: [
${entries.join("\n")}
    ],
  },
`;
  return `${head}${plugin.imp}import { defineConfig } from "vite";
${helper}
// Generated by s2s. The recovered code under src/_recovered/ builds as is; change this file only
// when the reconstruction needs it.
export default defineConfig({
  plugins: [${plugin.use}],
${resolve}  build: { outDir: "dist", emptyOutDir: true },
});
`;
}

export function tsconfig(target: Target, aliases: ProjectAlias[] = []): string {
  const paths =
    aliases.length === 0
      ? {}
      : {
          paths: Object.fromEntries(
            aliases.flatMap((a) => [
              [a.name, [a.entry]],
              [`${a.name}/*`, [`${a.root}/*`]],
            ]),
          ),
        };
  const jsx =
    target === "react"
      ? { jsx: "react-jsx" }
      : target === "preact"
        ? { jsx: "react-jsx", jsxImportSource: "preact" }
        : target === "vue"
          ? { jsx: "preserve" }
          : {};
  return `${JSON.stringify(
    {
      compilerOptions: {
        target: "ES2022",
        lib: ["ES2022", "DOM", "DOM.Iterable"],
        module: "ESNext",
        moduleResolution: "bundler",
        ...jsx,
        strict: true,
        noEmit: true,
        isolatedModules: true,
        skipLibCheck: true,
        // Recovered modules stay JavaScript until the agent converts them; they aren't checked.
        allowJs: true,
        checkJs: false,
        types: ["vite/client"],
        ...paths,
      },
      include: ["src"],
    },
    null,
    2,
  )}\n`;
}

/** The webpack runtime helpers the shim implements. */
export const SHIM_HELPERS = ["cw", "d", "n", "o", "r"];

/**
 * Stand-ins for the bundler runtime the recovered code still calls: `require(pkg)` for packages
 * Stage 4 left as CommonJS calls, and webpack's helpers. Loaded before any recovered module.
 */
export function runtimeShim(packages: string[], helpers: string[]): string {
  const binding = (_name: string, i: number) => `pkg${i}`;
  const imports = packages.map((p, i) => `import * as ${binding(p, i)} from ${JSON.stringify(p)};`);
  const table = packages.map((p, i) => `  ${JSON.stringify(p)}: ${binding(p, i)},`);
  const known: Record<string, string> = {
    cw: `// A CommonJS module evaluated on first use (webpack's \`require.cw\`).
require.cw = (factory: Factory | undefined) => {
  let module: { exports: Exports } | undefined;
  return () => {
    if (factory) {
      const run = factory;
      factory = undefined;
      module = { exports: {} };
      run.call(module.exports, module, module.exports);
    }
    return module?.exports;
  };
};`,
    n: `// The default export of a module, CommonJS or ES (webpack's \`require.n\`).
require.n = (mod: Exports) => {
  const getter = () => (mod && mod.__esModule ? mod.default : mod);
  return Object.assign(getter, { a: getter() });
};`,
    o: `require.o = (obj: object, key: PropertyKey) => Object.hasOwn(obj, key);`,
    d: `// Define export getters (webpack's \`require.d\`).
require.d = (exports: Exports, getters: Record<string, () => unknown>) => {
  for (const key of Object.keys(getters))
    if (!Object.hasOwn(exports, key)) Object.defineProperty(exports, key, { enumerable: true, get: getters[key] });
};`,
    r: `// Mark an object as an ES module namespace (webpack's \`require.r\`).
require.r = (exports: Exports) => {
  Object.defineProperty(exports, "__esModule", { value: true });
};`,
  };
  const used = helpers.filter((h) => h in known);
  return `// Generated by s2s: the bundler runtime the recovered code still relies on. Delete it once no
// module under src/_recovered/ calls \`require\` any more.
${imports.join("\n")}

type Exports = Record<string, unknown>;
type Factory = (module: { exports: Exports }, exports: Exports) => void;

const packages: Record<string, Exports> = {
${table.join("\n")}
};

/** A CommonJS package's \`module.exports\`, which bundlers expose as the default export. */
function interop(ns: Exports): unknown {
  const value = ns.default;
  return value !== null && (typeof value === "object" || typeof value === "function") ? value : ns;
}

function require(id: string): unknown {
  const ns = packages[id];
  if (!ns) throw new Error(\`s2s runtime: require("\${id}") is not an installed package\`);
  return interop(ns);
}
${used.map((h) => `\n${known[h]}`).join("\n")}

(globalThis as Record<string, unknown>).require = require;
`;
}

export function mainTs(input: { runtime: boolean; styles: string[]; modules: string[] }): string {
  const lines = [
    "// Generated by s2s: loads the recovered code in the order the site loaded it. As modules move out",
    "// of _recovered/, point these imports at their new homes.",
  ];
  if (input.runtime) lines.push('import "./_s2s/runtime.ts";');
  for (const s of input.styles) lines.push(`import ${JSON.stringify(s)};`);
  for (const m of input.modules) lines.push(`import ${JSON.stringify(m)};`);
  return `${lines.join("\n")}\n`;
}

