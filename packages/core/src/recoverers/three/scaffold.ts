export interface ThreeScaffoldOptions {
  assets: AssetMode;
  cloneRatio: number;
  cloneTexture: number;
}

export function threeOptions(raw: Record<string, unknown>): ThreeScaffoldOptions {
  const assets = (ASSET_MODES as readonly string[]).includes(String(raw.assets))
    ? (raw.assets as AssetMode)
    : "proxy";
  const ratio = Number(raw.cloneRatio);
  const size = Number(raw.cloneTexture);
  return {
    assets,
    cloneRatio: Number.isFinite(ratio) && ratio > 0 && ratio <= 1 ? ratio : DEFAULT_CLONE_RATIO,
    cloneTexture: Number.isInteger(size) && size >= 16 ? size : DEFAULT_CLONE_TEXTURE,
  };
}

async function codeFiles(dir: string): Promise<string[]> {
  if (!existsSync(dir)) return [];
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  return entries
    .filter((e) => e.isFile() && /\.[cm]?[jt]sx?$/.test(e.name))
    .map((e) => path.join(e.parentPath, e.name));
}

/** Where the site points three's loaders for their decoders, and which three folder serves each. */
export async function decoderMounts(
  projectSrc: string,
  decoderUrls: string[],
  siteOrigin: string,
): Promise<{ url: string; from: string }[]> {
  const mounts = new Map<string, string>();
  const add = (url: string, kind: "draco" | "basis", gltf: boolean) => {
    let pathname: string;
    try {
      const u = new URL(url, `${siteOrigin}/`);
      if (u.origin !== siteOrigin) return;
      pathname = u.pathname.endsWith("/") ? u.pathname : `${u.pathname}/`;
    } catch {
      return;
    }
    mounts.set(pathname, kind === "draco" ? (gltf ? "draco/gltf" : "draco") : "basis");
  };
  for (const file of await codeFiles(projectSrc)) {
    const text = await readFile(file, "utf8");
    for (const m of text.matchAll(/\.setDecoderPath\(\s*["'`]([^"'`]+)["'`]/g))
      add(m[1] as string, "draco", /gltf/.test(m[1] as string));
    for (const m of text.matchAll(/\.setTranscoderPath\(\s*["'`]([^"'`]+)["'`]/g))
      add(m[1] as string, "basis", false);
  }
  for (const url of decoderUrls) {
    const dir = url.replace(/[^/]*$/, "");
    if (/draco/i.test(url)) add(dir, "draco", /gltf/i.test(url));
    else if (/basis/i.test(url)) add(dir, "basis", false);
  }
  return [...mounts]
    .map(([url, from]) => ({ url, from }))
    .sort((a, b) => a.url.localeCompare(b.url));
}

/** A Vite plugin that serves and copies three's own decoders at the paths the site expects. */
export function decodersPlugin(mounts: { url: string; from: string }[]): string {
  return `// Generated by s2s. three's Draco and Basis decoders, served from the installed \`three\`
// package at the paths the site's loaders ask for, instead of copies of the site's files.
import { cpSync, existsSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { Plugin } from "vite";

const MOUNTS: { url: string; from: string }[] = ${JSON.stringify(mounts, null, 2)};

function libs(): string {
  // "three" resolves to build/three.module.js; the decoders live in examples/jsm/libs/.
  const entry = fileURLToPath(import.meta.resolve("three"));
  return path.resolve(path.dirname(entry), "..", "examples", "jsm", "libs");
}

export default function s2sDecoders(): Plugin {
  let outDir = "dist";
  return {
    name: "s2s-decoders",
    configResolved(config) {
      outDir = path.resolve(config.root, config.build.outDir);
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const url = (req.url ?? "").split("?")[0] ?? "";
        const mount = MOUNTS.find((m) => url.startsWith(m.url));
        if (!mount) return next();
        const file = path.join(libs(), mount.from, url.slice(mount.url.length));
        if (!existsSync(file) || !statSync(file).isFile()) return next();
        res.setHeader("content-type", file.endsWith(".wasm") ? "application/wasm" : "text/javascript");
        res.end(readFileSync(file));
      });
    },
    closeBundle() {
      for (const mount of MOUNTS) {
        const from = path.join(libs(), mount.from);
        if (existsSync(from)) cpSync(from, path.join(outDir, mount.url), { recursive: true });
      }
    },
  };
}
`;
}

const LAYOUT: Record<string, string> = {
  scene:
    "Scene setup: renderer, scene, cameras, lights, environment, the render loop. `graph.json` is the captured hierarchy at the first keyframe; keep its node names, verify compares them.",
  objects:
    "One module per object or group in the scene (a model and the code that places and animates it).",
  materials: "Materials, one module each, named after the material (`GlowMaterial`).",
  shaders: "GLSL, imported with `?raw`. s2s recovered these from the bundle; edit them here.",
  timeline:
    "The scroll and time choreography (GSAP timelines, ScrollTrigger, Lenis), in one module.",
  interaction: "Pointer, keyboard and resize handling, raycasting.",
};

const R3F_LAYOUT: Record<string, string> = {
  ...LAYOUT,
  components:
    "React Three Fiber components, one per object, named after the scene node (`<Car />` for `Car`).",
};
delete (R3F_LAYOUT as Record<string, string | undefined>).objects;

/**
 * The three recoverer's scaffold step, after the generic files and before install and build:
 * assets for the chosen mode, ASSETS.md, decoders, the layout folders and the local-only notices.
 */
export async function threeScaffold(ctx: ScaffoldHookContext): Promise<void> {
  const { paths, framework } = ctx;
  const opts = threeOptions(ctx.options);
  framework.details.assets = opts.assets;
  const manifest = JSON.parse(await readFile(paths.manifest, "utf8")) as { targetUrl: string };
  const site = manifest.targetUrl;
  const origin = new URL(site).origin;
  const r3f = framework.flavour === "r3f";

  // 1. Assets.
  const assets = await buildAssets(paths, site, {
    mode: opts.assets,
    cloneRatio: opts.cloneRatio,
    cloneTexture: opts.cloneTexture,
    warn: ctx.warn,
  });

  // 2. Decoders from the three package, at the paths the site's loaders use.
  const records = await readRequestLog(paths.requests).catch(() => []);
  const decoderUrls = records
    .filter((r) => r.tags?.some((t) => t.startsWith("decoder:")))
    .map((r) => r.url);
  const mounts = await decoderMounts(path.join(paths.project, "src"), decoderUrls, origin);
  if (mounts.length > 0) {
    await writeFileAtomic(path.join(paths.project, "s2s-decoders.ts"), decodersPlugin(mounts));
    const configFile = path.join(paths.project, "vite.config.ts");
    let config = await readFile(configFile, "utf8");
    config = `import s2sDecoders from "./s2s-decoders";\n${config}`.replace(
      /plugins: \[([^\]]*)\]/,
      (_, inner: string) => `plugins: [${inner ? `${inner}, ` : ""}s2sDecoders()]`,
    );
    await writeFileAtomic(configFile, config);
  }

  // 3. Layout folders, each saying what moves there, and the captured graph.
  const layout = r3f ? R3F_LAYOUT : LAYOUT;
  for (const [dir, text] of Object.entries(layout)) {
    await mkdir(path.join(paths.project, "src", dir), { recursive: true });
    await writeFileAtomic(
      path.join(paths.project, "src", dir, "README.md"),
      `# src/${dir}\n\n${text}\n`,
    );
  }
  await mkdir(path.join(paths.project, "public", "models"), { recursive: true });
  const index = await readWebglIndex(paths);
  const first = index?.pages[0]?.viewports[0];
  let graphNodes = 0;
  if (index && first) {
    const snaps = await readKeyframes(paths, index.pages[0]?.slug as string, first.viewport, [
      first.keyframes[0]?.id ?? "t0",
    ]);
    const snap = [...snaps.values()][0];
    if (snap) {
      const graph = snap.scenes.map((s) => ({
        scene: s.name,
        camera: s.camera?.path ?? null,
        nodes: s.nodes.map((n) => ({
          path: n.path,
          type: n.type,
          ...(n.material ? { materials: n.material.map((m) => m?.name ?? m?.type ?? null) } : {}),
        })),
      }));
      graphNodes = graph.reduce((n, s) => n + s.nodes.length, 0);
      await writeJsonAtomic(path.join(paths.project, "src", "scene", "graph.json"), graph);
    }
  }

  // 4. Local-only notices.
  if (assets.localOnly) {
    const readme = path.join(paths.project, "README.md");
    const existing = await readFile(readme, "utf8").catch(() => "");
    if (!existing.includes(LOCAL_ONLY_NOTICE))
      await writeFileAtomic(
        readme,
        `> **Local study only.** ${LOCAL_ONLY_NOTICE} See \`ASSETS.md\`.\n\n${existing}`,
      );
  }

  // 5. Facts for the summary and AGENTS.md.
  const models = assets.assets.filter((a) => a.type === "model").length;
  const shaders = await readFile(path.join(paths.analysis, "shaders.json"), "utf8")
    .then((t) => JSON.parse(t) as { programs: { builtin: boolean }[] })
    .catch(() => ({ programs: [] }));
  const custom = shaders.programs.filter((p) => !p.builtin).length;
  const keyframes =
    index?.pages.reduce((n, p) => n + (p.viewports[0]?.keyframes.length ?? 0), 0) ?? 0;
  framework.details.summary = summaryText(
    framework.version,
    models,
    opts.assets,
    custom,
    keyframes,
  );
  framework.details.decoders = mounts.map((m) => m.url);
  ctx.stats.models = models;
  ctx.stats.customShaders = custom;
  ctx.stats.keyframes = keyframes;
  ctx.stats.sceneNodes = graphNodes;
  ctx.details.assets = opts.assets;
  ctx.details.cloneRatio = opts.cloneRatio;
  ctx.details.cloneTexture = opts.cloneTexture;
  ctx.details.webglSummary = framework.details.summary as string;
  ctx.details.localOnly = assets.localOnly;
  ctx.details.leakCheck = assets.checks.leak ? assets.checks.leak.passed : null;
  ctx.details.cloneBudgets = assets.checks.budgets ? assets.checks.budgets.passed : null;
  await writeJsonAtomic(path.join(paths.analysis, "framework.json"), framework);
}

const MODE_WORD: Record<AssetMode, string> = {
  proxy: "proxies",
  clone: "clones",
  original: "originals",
};

/** "three r187 · 12 models → proxies · 9 custom shaders · 24 keyframes". */
export function summaryText(
  version: string | null,
  models: number,
  mode: AssetMode,
  shaders: number,
  keyframes: number,
): string {
  const rev = version?.replace(/^0\./, "") ?? "?";
  const s = (n: number, w: string) => `${n} ${w}${n === 1 ? "" : "s"}`;
  return `three r${rev} · ${s(models, "model")} → ${MODE_WORD[mode]} · ${s(shaders, "custom shader")} · ${s(keyframes, "keyframe")}`;
}
